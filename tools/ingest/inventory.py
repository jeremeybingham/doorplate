#!/usr/bin/env python3
"""One table of what is in `local-data/`: the record files and the harness runs, with row counts.

    python tools/ingest/inventory.py                       # prints the tables and writes local-data/INVENTORY.md
    python tools/ingest/inventory.py --exclude netsyms-2026/records --exclude nad-2026

It reads the `records.json` written beside every `records*.parquet` (tools/ingest) and the
`manifest.json` and `DONE` of every run under `local-data/netsyms-runs/` (tools/harness), and prints:

- the record files: source, rows by role, when and at which commit they were made;
- the runs: id, date, input, schema version, rows, how many were flagged, whether the run is
  complete (`DONE`), a test slice (`LIMITED`) or unfinished;
- the rows examined: the rows of the **latest complete run per input file**, in total (record files with no complete run
  are listed apart, not counted). Several
  inputs overlap (a sample inside a full database, two files of the same voters), so the total is
  an upper bound; `--exclude TEXT` leaves out runs whose input path or source contains TEXT, and
  the report lists what it left out.

Counts only: no row, name or address is read or printed. The file is private by location
(`local-data/` is git-ignored); the aggregate counts may be quoted (docs/data-policy.md). This
library formats and parses; it does not validate that an address exists or can receive mail.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCAL = ROOT / "local-data"


def load(path):
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return None


def record_files(local):
    out = []
    for p in sorted(local.glob("*/records*.json")):
        d = load(p)
        if d and "rows" in d:
            out.append({"folder": p.parent.name, "file": p.with_suffix(".parquet").name, "source": d.get("source", p.stem),
                        "rows": d["rows"], "roles": {r: v.get("rows", 0) for r, v in d.get("roles", {}).items()},
                        "created": (d.get("created_at") or "")[:10], "commit": d.get("commit", "")})
    return out


def runs(local):
    out = []
    for m in sorted((local / "netsyms-runs").glob("*/manifest.json")):
        d = load(m)
        if not d:
            continue
        run = m.parent
        done = load(run / "DONE")
        state = "complete" if done else "limited" if (run / "LIMITED").exists() else "unfinished"
        info = load(run / "LIMITED") if state == "limited" else done
        inp = d.get("input", {})
        out.append({"id": d.get("run_id", run.name), "date": (d.get("started") or "")[:10], "state": state,
                    "schema": d.get("schema_version"), "input": inp.get("path", ""), "kind": inp.get("kind", "netsyms-sqlite"),
                    "rows": (info or {}).get("rows", 0), "flagged": (info or {}).get("flagged", 0), "started": d.get("started", "")})
    return out


def examined(all_runs, excludes, local):
    """The latest complete run per input file, and the runs left out by --exclude."""
    keep, left = {}, []
    for r in all_runs:
        if r["state"] != "complete":
            continue
        if any(x in rel(r["input"], local) for x in excludes):
            left.append(r)
            continue
        if r["input"] not in keep or r["started"] > keep[r["input"]]["started"]:
            keep[r["input"]] = r
    return sorted(keep.values(), key=lambda r: -r["rows"]), left


def rel(path, local):
    """The path relative to local-data when it is under it (inputs are stored as absolute paths)."""
    try:
        return str(Path(path).resolve().relative_to(local.resolve()))
    except (ValueError, OSError):
        return Path(path).name


def table(header, rows):
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def build(local, excludes):
    recs, all_runs = record_files(local), runs(local)
    keep, left = examined(all_runs, excludes, local)
    ran = {rel(r["input"], local) for r in all_runs if r["state"] == "complete"}
    unrun = [r for r in recs if f"{r['folder']}/{r['file']}" not in ran]
    total = sum(r["rows"] for r in keep)
    out = ["# Inventory of local-data (generated by tools/ingest/inventory.py)", "",
           "Counts only. Private by location (`local-data/` is git-ignored); the aggregate counts may be quoted "
           "(docs/data-policy.md). What each folder is, its provenance and its terms: `README.md` here and each "
           "folder's `NOTICE.md` and `INVENTORY.md`.", "", "## Record files (tools/ingest)", ""]
    out += table(["source", "file", "rows", "by role", "made", "commit"],
                 [(r["source"], f"{r['folder']}/{r['file']}", f"{r['rows']:,}",
                   ", ".join(f"{k} {v:,}" for k, v in r["roles"].items()), r["created"], r["commit"]) for r in recs])
    out += ["", "## Harness runs (tools/harness)", ""]
    out += table(["run", "date", "input", "schema", "rows", "flagged", "state"],
                 [(r["id"], r["date"], rel(r["input"], local) + (" (SQLite)" if r["kind"] != "records" else ""), r["schema"],
                   f"{r['rows']:,}", f"{100 * r['flagged'] / r['rows']:.1f}%" if r["rows"] else "-", r["state"])
                  for r in sorted(all_runs, key=lambda r: r["started"])])
    out += ["", "## Rows examined", "",
            "The latest complete run per input file. Inputs overlap (a sample inside a full database, two files "
            "of the same voters), so the total is an upper bound on distinct addresses.", ""]
    out += table(["input", "run", "rows"], [(rel(r["input"], local), r["id"], f"{r['rows']:,}") for r in keep])
    out += ["", f"**Total: {total:,} rows** in {len(keep)} inputs."]
    if left:
        out += ["", "Left out by `--exclude`: " + ", ".join(sorted({rel(r['input'], local) for r in left})) + "."]
    if unrun:
        out += ["", "Record files with no complete harness run (not in the total; some were scored with "
                    "`label_score.py`, which keeps no run record): "
                + ", ".join(f"{r['folder']}/{r['file']} ({r['rows']:,})" for r in unrun) + "."]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--local", type=Path, default=LOCAL, help="the local-data folder")
    ap.add_argument("--exclude", action="append", default=[], metavar="TEXT",
                    help="leave out of the total the runs whose input path or folder contains TEXT")
    ap.add_argument("--out", type=Path, help="where to write (default: INVENTORY.md in the local-data folder)")
    args = ap.parse_args(argv)
    if not args.local.is_dir():
        sys.exit(f"{args.local} not found")
    text = build(args.local, args.exclude)
    (args.out or args.local / "INVENTORY.md").write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())

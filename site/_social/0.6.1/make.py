def page(title, w, h, css, body):
    return (
        f'<!doctype html>\n<html lang="en"><head><meta charset="utf-8">\n<title>{title}</title>\n'
        f"<style>\n  /* Generated by make.py; edit the data there, not here. */{BASE_CSS}"
        f"  body{{width:{w}px;height:{h}px}}\n{css}</style></head>\n<body>\n{body}\n</body></html>\n"
    )


def fmt_us(v):
    return f"{v:.1f}" if v >= 10 else f"{v:.2f}"


def bar_chart_svg(
    w,
    h,
    values,
    label_fmt,
    highlight,
    *,
    x_pad=70,
    top=36,
    bottom=44,
    font=22,
    rules=None,
):
    """Vertical bars per release, starting at zero, value on top, release under."""
    vmax = max(values.values()) * 1.08
    plot_h = h - top - bottom
    slot = (w - x_pad) / len(RELEASES)
    bw = slot * 0.56
    out = [
        f'<svg width="{w}" height="{h}" viewBox="0 0 {w} {h}" xmlns="http://www.w3.org/2000/svg">'
    ]
    base_y = top + plot_h
    out.append(
        f'<line x1="{x_pad - 10}" x2="{w}" y1="{base_y}" y2="{base_y}" stroke="{RULE}" stroke-width="2"/>'
    )
    for i, r in enumerate(RELEASES):
        v = values[r]
        cx = x_pad + slot * i + slot / 2
        bh = plot_h * v / vmax
        if r == highlight:
            color = BLUE
        elif rules is not None:
            color = GREY if r in rules else "#6f9bd1"
        else:
            color = GREY
        x, y = cx - bw / 2, base_y - bh
        out.append(
            f'<path d="M{x:.1f},{base_y} V{y + 4:.1f} Q{x:.1f},{y:.1f} {x + 4:.1f},{y:.1f} H{x + bw - 4:.1f} '
            f'Q{x + bw:.1f},{y:.1f} {x + bw:.1f},{y + 4:.1f} V{base_y} Z" fill="{color}"/>'
        )
        weight = 800 if r == highlight else 700
        tcol = BLUE if r == highlight else INK
        out.append(
            f'<text x="{cx:.1f}" y="{y - 10:.1f}" text-anchor="middle" font-size="{font}" font-weight="{weight}" '
            f'fill="{tcol}">{label_fmt(v)}</text>'
        )
        out.append(
            f'<text x="{cx:.1f}" y="{base_y + 30}" text-anchor="middle" font-size="{font}" '
            f'font-weight="{weight}" fill="{tcol if r == highlight else INK2}">{r}</text>'
        )
    out.append("</svg>")
    return "\n".join(out)



def plateau():
    css = """
  body{padding:30px 44px 22px}
  h1{font-size:32px;font-weight:800;letter-spacing:-1px}
  .sub{font-size:19px;color:var(--ink2);margin:4px 0 14px;line-height:1.3}
  .row{display:flex;gap:18px}
  .p{flex:none}
  .p h2{font-size:19px;font-weight:700;line-height:1.2;height:48px}
  .k5{flex:1;min-width:0;border-left:2px solid var(--rule);padding-left:18px}
  .k5 h2{font-size:19px;font-weight:700;line-height:1.2;margin-bottom:8px}
  .k5 .r{display:flex;justify-content:space-between;gap:10px;font-size:16px;color:var(--ink2);border-top:1px solid var(--rule);padding:7px 0;line-height:1.2}
  .k5 .r b{color:var(--ink);font-size:19px;font-variant-numeric:tabular-nums;white-space:nowrap}
  .k5 .s{margin-top:8px;font-size:19px;font-weight:700;line-height:1.25}
  .k5 .s em{font-style:normal;color:var(--doorplate)}
  .foot{font-size:15px;line-height:1.35;color:var(--ink2);margin-top:12px}
"""
    span = 3.0  # every panel shows the same 3-point span, so slopes compare
    panels = []
    for title, series, n, lo in (
        ("Everyday addresses<br>(suite natural, 16,001)", NATURAL, N["natural"], 96.8),
        ("Whole suite<br>(19,586)", WHOLE, N["whole"], 91.6),
        ("Geocode benchmark<br>(dev split, 60,522)", DEV, N["dev"], 92.9),
    ):
        w, h, xl, top, bot = 206, 320, 46, 14, 50
        hi = lo + span
        pw, ph = w - xl - 10, h - top - bot

        def x(i, pw=pw, xl=xl):
            return xl + pw * i / (len(RELEASES) - 1)

        def y(v, lo=lo, hi=hi, ph=ph, top=top):
            return top + ph * (hi - v) / (hi - lo)

        s = [
            f'<svg width="{w}" height="{h}" viewBox="0 0 {w} {h}" xmlns="http://www.w3.org/2000/svg">'
        ]
        g = math.ceil(lo)
        while g <= hi:
            s.append(
                f'<line x1="{xl}" x2="{w - 4}" y1="{y(g):.1f}" y2="{y(g):.1f}" stroke="{RULE}" stroke-width="1"/>'
            )
            s.append(
                f'<text x="{xl - 8}" y="{y(g) + 6:.1f}" text-anchor="end" font-size="16" fill="{MUTED}">{g}%</text>'
            )
            g += 1
        # 95% interval band (normal approximation) around each point
        up, dn = [], []
        for i, r in enumerate(RELEASES):
            p = series[r] / 100
            hw = 1.96 * math.sqrt(p * (1 - p) / n) * 100
            up.append(f"{x(i):.1f},{y(series[r] + hw):.1f}")
            dn.append(f"{x(i):.1f},{y(series[r] - hw):.1f}")
        s.append(
            f'<polygon points="{" ".join(up + dn[::-1])}" fill="{BLUE}" fill-opacity="0.16"/>'
        )
        pts = " ".join(f"{x(i):.1f},{y(series[r]):.1f}" for i, r in enumerate(RELEASES))
        s.append(
            f'<polyline points="{pts}" fill="none" stroke="{BLUE}" stroke-width="2.5"/>'
        )
        for i, r in enumerate(RELEASES):
            s.append(
                f'<circle cx="{x(i):.1f}" cy="{y(series[r]):.1f}" r="4.5" fill="{BLUE}" stroke="{SURFACE}" stroke-width="2"/>'
            )
        first, last = series[RELEASES[0]], series[RELEASES[-1]]
        s.append(
            f'<text x="{x(0):.1f}" y="{y(first) + 26:.1f}" text-anchor="start" font-size="17" font-weight="700" fill="{INK}">{first:.1f}</text>'
        )
        s.append(
            f'<text x="{x(len(RELEASES) - 1):.1f}" y="{y(last) - 14:.1f}" text-anchor="end" font-size="17" font-weight="700" fill="{INK}">{last:.1f}</text>'
        )
        for i in (0, len(RELEASES) - 1):
            s.append(
                f'<text x="{x(i):.1f}" y="{h - 18}" text-anchor="{"start" if i == 0 else "end"}" font-size="16" fill="{INK2}">{RELEASES[i]}</text>'
            )
        s.append("</svg>")
        panels.append(f'<section class="p"><h2>{title}</h2>{"".join(s)}</section>')
    k5 = "".join(
        f'<div class="r"><span>{name}</span><b>{rows:,}</b></div>'
        for name, rows in K5_ROWS
    )
    body = f"""  <h1>The benchmarks stopped moving; the parser did not</h1>
  <div class="sub">Whole address right, 0.3.1 to 0.6.1, each panel the same 3-point span; the band is the 95% interval of each score.</div>
  <div class="row">
{"".join(panels)}
  <section class="k5"><h2>Rows four of the 0.6.0 rules read differently in the full NAD and Netsyms files</h2>{k5}
    <div class="s">On the benchmark suite the same rules gained <em>3 records</em> and lost none.</div></section>
  </div>
  <div class="foot">Suite v1 (frozen labels), coarse labels, usaddress&rsquo;s scoring; the 0.6.0 step in the whole suite is one label (the W in W 615 ELM ST). Rows: CHANGELOG 0.6.0. Figures: docs/benchmarks.md.</div>"""
    return page(
        "doorplate: the accuracy plateau, 0.3.1 to 0.6.1 (blog chart, 1080 x 680)",
        1080,
        680,
        css,
        body,
    )


def main():
    from playwright.sync_api import sync_playwright

    jobs = (
        ("graphic", graphic(), 1350, "doorplate-0-6-1.png"),
        ("cycle", cycle(), 860, "doorplate-0-6-1-cycle.png"),
        ("plateau", plateau(), 680, "doorplate-0-6-1-plateau.png"),
    )
    chrome = (
        sys.argv[1]
        if len(sys.argv) > 1
        else str(
            pathlib.Path.home()
            / ".cache/ms-playwright/chromium-1243/chrome-linux64/chrome"
        )
    )
    with sync_playwright() as p:
        b = p.chromium.launch(executable_path=chrome)
        for name, html, h, asset in jobs:
            (HERE / f"{name}.html").write_text(html)
            pg = b.new_page(
                viewport={"width": 1080, "height": h}, device_scale_factor=1
            )
            pg.goto((HERE / f"{name}.html").as_uri())
            print(
                name,
                "content height",
                pg.evaluate("document.documentElement.scrollHeight"),
                "of",
                h,
            )
            pg.screenshot(path=str(HERE / f"{name}.png"))
            shutil.copyfile(HERE / f"{name}.png", ASSETS / asset)
        b.close()


if __name__ == "__main__":
    main()

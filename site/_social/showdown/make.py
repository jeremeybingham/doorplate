"""Graphics for the showdown post: writes HTML sources and renders PNGs.

    score.html  -> score.png   1080 x 760   Parser Score with 95% intervals (site/assets/showdown-score.png)
    parts.html  -> parts.png   1080 x 900   record accuracy per part          (site/assets/showdown-parts.png)
    speed.html  -> speed.png   1080 x 560   speed, memory, install size       (site/assets/showdown-speed.png)

Every figure is copied from report/REPORT.md of address-parser-showdown (v0.1.0, run 2026-11-16, sections 7.2, 7.3, 8).
    uv venv /tmp/pw && uv pip install -p /tmp/pw/bin/python playwright
    /tmp/pw/bin/python make.py [path/to/chrome]
"""

import pathlib, shutil, sys

HERE = pathlib.Path(__file__).resolve().parent
ASSETS = HERE.parent.parent / "assets"
P = ["doorplate", "usaddress", "libpostal"]
COL = {"doorplate": "#2a78d6", "usaddress": "#9aa7b8", "libpostal": "#c9c6bd"}
INK, INK2, RULE = "#0b0b0b", "#52514e", "#e3e2de"
FONT = '"DejaVu Sans","Helvetica Neue",Arial,sans-serif'

# Report 7.2: score, low, high
SCORE = {
    "doorplate": (90.9, 89.8, 92.0),
    "usaddress": (84.7, 83.4, 86.0),
    "libpostal": (80.8, 79.5, 82.2),
}
# Report 7.3: coarse record accuracy (neutral and golden parts)
PARTS = [
    ("Golden: normal (1,568)", 95.0, 93.6, 91.8),
    ("Golden: hard (556)", 91.2, 88.5, 70.9),
    ("Golden: nightmare (226)", 69.0, 51.3, 54.0),
    ("Suite: natural (16,001)", 98.6, 96.5, 95.0),
    ("Suite: hand (1,000)", 95.8, 91.1, 84.0),
    ("Senzing US: osm (2,172)", 98.1, 90.6, 98.8),
    ("Geocode dev (60,522)", 94.4, 88.4, 79.9),
]
# Report 8: one process, strings per second; memory MB after loading; install MB
SPEED = [
    ("Strings per second (1 process)", (72028, 8952, 14577), "{:,.0f}"),
    ("Memory after loading (MB)", (27, 27, 2958), "{:,.0f}"),
    ("Install size (MB)", (4.9, 4.8, 2993.1), "{:,.1f}"),
]

CSS = f"""*{{box-sizing:border-box;margin:0;padding:0}}html,body{{background:#fff}}
body{{font-family:{FONT};color:{INK};overflow:hidden;padding:36px 48px 24px}}
h1{{font-size:38px;font-weight:800;letter-spacing:-1px;line-height:1.1}}
.sub{{font-size:21px;color:{INK2};margin:8px 0 16px;line-height:1.3}}
.foot{{font-size:16px;color:{INK2};margin-top:10px;line-height:1.35}}
.leg{{display:flex;gap:22px;font-size:19px;margin-bottom:10px}}.leg i{{display:inline-block;width:16px;height:16px;border-radius:3px;margin-right:7px;vertical-align:-2px}}
text{{font-family:{FONT}}}"""


def page(title, w, h, body):
    return (
        f'<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><title>{title}</title>\n'
        f"<style>/* Generated by make.py; edit the data there. */{CSS}body{{width:{w}px;height:{h}px}}</style></head>\n<body>\n{body}\n</body></html>\n"
    )


def legend():
    return (
        '<div class="leg">'
        + "".join(f'<span><i style="background:{COL[p]}"></i>{p}</span>' for p in P)
        + "</div>"
    )


def score():
    w, h, x0, x1 = 984, 420, 200, 880
    lo, hi = 70.0, 95.0
    X = lambda v: x0 + (v - lo) / (hi - lo) * (x1 - x0)
    s = [f'<svg width="{w}" height="{h}" xmlns="http://www.w3.org/2000/svg">']
    for t in range(70, 96, 5):
        s.append(
            f'<line x1="{X(t)}" x2="{X(t)}" y1="10" y2="{h - 40}" stroke="{RULE}"/><text x="{X(t)}" y="{h - 14}" text-anchor="middle" font-size="18" fill="{INK2}">{t}</text>'
        )
    for i, p in enumerate(P):
        v, a, b = SCORE[p]
        y = 40 + i * 120
        s.append(
            f'<text x="{x0 - 14}" y="{y + 38}" text-anchor="end" font-size="26" font-weight="700">{p}</text>'
        )
        s.append(
            f'<rect x="{x0}" y="{y}" width="{X(v) - x0}" height="64" rx="4" fill="{COL[p]}"/>'
        )
        s.append(
            f'<line x1="{X(a)}" x2="{X(b)}" y1="{y + 32}" y2="{y + 32}" stroke="{INK}" stroke-width="3"/><line x1="{X(a)}" x2="{X(a)}" y1="{y + 22}" y2="{y + 42}" stroke="{INK}" stroke-width="3"/><line x1="{X(b)}" x2="{X(b)}" y1="{y + 22}" y2="{y + 42}" stroke="{INK}" stroke-width="3"/>'
        )
        s.append(
            f'<text x="{X(b) + 12}" y="{y + 42}" font-size="34" font-weight="800" fill="{COL[p] if p == "doorplate" else INK}">{v}</text>'
        )
    s.append("</svg>")
    body = (
        f"<h1>Parser Score: doorplate 90.9, usaddress 84.7, libpostal 80.8</h1>"
        f'<div class="sub">Coarse record accuracy, half on the golden set&rsquo;s three tiers and half on four neutral sets. The black line is the 95% bootstrap interval; the axis starts at 70.</div>'
        + "".join(s)
        + '<div class="foot">address-parser-showdown v0.1.0, run 2026-11-16, formula v1 fixed before the first run. The ranking holds with every set left out.</div>'
    )
    return page("Parser Score", 1080, 700, body)


def parts():
    w, rowh = 984, 112
    x0, x1 = 320, 900
    X = lambda v: x0 + v / 100 * (x1 - x0)
    h = 40 + rowh * len(PARTS)
    s = [f'<svg width="{w}" height="{h}" xmlns="http://www.w3.org/2000/svg">']
    for t in (0, 25, 50, 75, 100):
        s.append(
            f'<line x1="{X(t)}" x2="{X(t)}" y1="0" y2="{h - 30}" stroke="{RULE}"/><text x="{X(t)}" y="{h - 8}" text-anchor="middle" font-size="16" fill="{INK2}">{t}%</text>'
        )
    for i, row in enumerate(PARTS):
        y = 8 + i * rowh
        s.append(
            f'<text x="{x0 - 12}" y="{y + 50}" text-anchor="end" font-size="19" font-weight="700">{row[0]}</text>'
        )
        for j, p in enumerate(P):
            v = row[1 + j]
            by = y + j * 30
            s.append(
                f'<rect x="{x0}" y="{by}" width="{X(v) - x0}" height="26" rx="3" fill="{COL[p]}"/>'
                f'<text x="{X(v) + 8}" y="{by + 20}" font-size="17" font-weight="{800 if p == "doorplate" else 500}">{v}</text>'
            )
    s.append("</svg>")
    body = (
        "<h1>Record accuracy on every scored part</h1>"
        '<div class="sub">A record is right when every field the gold has matches in span and label. Every set that goes into the score is shown, nothing left out.</div>'
        + legend()
        + "".join(s)
    )
    return page("Per part", 1080, 140 + h + 40, body)


def speed():
    pw, ph = 320, 330
    s = []
    for k, (title, vals, f) in enumerate(SPEED):
        m = max(vals)
        x = k * (pw + 12)
        g = [
            f'<svg width="{pw}" height="{ph}" xmlns="http://www.w3.org/2000/svg">',
            f'<text x="0" y="22" font-size="17" font-weight="700">{title}</text>',
        ]
        base = ph - 36
        top = 70
        for j, p in enumerate(P):
            bh = max(2, (base - top) * vals[j] / m)
            bx = 14 + j * 100
            g.append(
                f'<rect x="{bx}" y="{base - bh}" width="84" height="{bh}" rx="4" fill="{COL[p]}"/>'
                f'<text x="{bx + 42}" y="{base - bh - 8}" text-anchor="middle" font-size="18" font-weight="800">{f.format(vals[j])}</text>'
                f'<text x="{bx + 42}" y="{ph - 12}" text-anchor="middle" font-size="15" fill="{INK2}">{p}</text>'
            )
        g.append("</svg>")
        s.append("".join(g))
    body = (
        "<h1>Five to eight times faster, in 27 MB</h1>"
        '<div class="sub">100,000 strings, median of 5 passes, i9-9900K under WSL2. Speed is never part of the Parser Score.</div>'
        f'<div style="display:flex;gap:12px">{"".join(s)}</div>'
        '<div class="foot">With 4 processes: 223,510 / 28,054 / 43,951 strings per second. Load time: 0.003 s / 0.012 s / 3.48 s.</div>'
    )
    return page("Speed and size", 1080, 560, body)


def main():
    from playwright.sync_api import sync_playwright

    chrome = (
        sys.argv[1]
        if len(sys.argv) > 1
        else str(
            pathlib.Path.home()
            / ".cache/ms-playwright/chromium-1243/chrome-linux64/chrome"
        )
    )
    jobs = [
        ("score", score(), 1080, 700),
        ("parts", parts(), 1080, None),
        ("speed", speed(), 1080, 560),
    ]
    with sync_playwright() as p:
        b = p.chromium.launch(executable_path=chrome)
        for name, html, w, h in jobs:
            (HERE / f"{name}.html").write_text(html)
            pg = b.new_page(
                viewport={"width": w, "height": h or 1000}, device_scale_factor=1
            )
            pg.goto((HERE / f"{name}.html").as_uri())
            if h is None:
                h = pg.evaluate("document.body.scrollHeight")
                pg.set_viewport_size({"width": w, "height": h})
            pg.screenshot(
                path=str(HERE / f"{name}.png"),
                clip={"x": 0, "y": 0, "width": w, "height": h},
            )
            shutil.copy(HERE / f"{name}.png", ASSETS / f"showdown-{name}.png")
        b.close()


main()
